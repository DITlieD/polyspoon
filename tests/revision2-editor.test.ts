import test from 'node:test';
import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { createServer, preview } from 'vite';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import type { Design } from '../src/catalog/index.ts';
import { sourceProvenance } from '../scripts/provenance.ts';

interface Api {
  configuration():Design;
  camera():unknown;
  select(id:string):boolean;
  diagnostic(enabled:boolean):void;
  projected():number[][];
  selectRole(role:string):void;
}
test('revision 2 real editor interactions and first visual pass',{timeout:120000},async()=>{
  const integration=process.env.INTEGRATION_EVIDENCE_ROOT;
  const server=integration ? await preview({build:{outDir:integration+'/build'},preview:{host:'127.0.0.1',port:0},logLevel:'error'}) : await createServer({server:{host:'127.0.0.1',port:0},logLevel:'error'});
  if('listen' in server) await server.listen();
  const browser=await chromium.launch({executablePath:process.env.CHROME_PATH??'/usr/bin/google-chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader','--disable-dev-shm-usage']});
  const page=await browser.newPage({viewport:{width:1440,height:960},deviceScaleFactor:1,acceptDownloads:true});
  const errors:string[]=[],screenshots:Record<string,string>={};
  page.on('pageerror',e=>errors.push(e.message));
  const directory=integration?integration+'/editor':'evidence/revision2/editor';
  await mkdir(directory,{recursive:true});
  const config=()=>page.evaluate(()=>(window.workshopDiagnostics as unknown as Api).configuration());
  const capture=async(name:string)=>{
    await page.waitForTimeout(100);
    const bytes=await page.screenshot({path:directory+'/'+name+'.png',fullPage:true});
    screenshots[name]=createHash('sha256').update(bytes).digest('hex');
  };
  try {
    await page.goto(server.resolvedUrls!.local[0]+'?diagnostic=1');
    await page.waitForFunction(()=>Boolean(window.workshopDiagnostics));
    await page.evaluate(()=>{document.body.classList.remove('diagnostic');(window.workshopDiagnostics as unknown as Api).diagnostic(false);});
    await capture('desktop-lantern-shape');
    const width=page.locator('[id="bodyWidth"]'), slider=page.locator('[id="bodyWidth-slider"]');
    await width.fill('39.2');
    assert.equal(await page.locator('#save').isDisabled(),true);
    assert.equal((await config()).applied.bodyWidth,0.32);
    await width.press('Enter');
    assert.equal((await config()).applied.bodyWidth,0.392);
    assert.equal(await page.locator('#save').isDisabled(),false);
    await page.locator('#undo').click();
    assert.equal((await config()).applied.bodyWidth,0.32);
    const cameraBefore=await page.evaluate(()=>(window.workshopDiagnostics as unknown as Api).camera());
    await slider.evaluate(node=>{(window as unknown as {originalSlider:Element}).originalSlider=node;});
    const bounds=(await slider.boundingBox())!;
    await page.mouse.move(bounds.x+bounds.width*0.45,bounds.y+bounds.height/2);
    await page.mouse.down();
    await page.mouse.move(bounds.x+bounds.width*0.7,bounds.y+bounds.height/2,{steps:8});
    await page.mouse.up();
    assert.equal(await slider.evaluate(node=>(window as unknown as {originalSlider:Element}).originalSlider===node),true);
    assert.deepEqual(await page.evaluate(()=>(window.workshopDiagnostics as unknown as Api).camera()),cameraBefore);
    const dragged=(await config()).applied.bodyWidth;
    assert.notEqual(dragged,0.32);
    await page.locator('#undo').click();assert.equal((await config()).applied.bodyWidth,0.32);
    await page.locator('#redo').click();assert.equal((await config()).applied.bodyWidth,dragged);
    await width.fill('100');await width.press('Enter');
    assert.equal((await config()).applied.bodyWidth,dragged);
    assert.equal(await page.locator('#export').isDisabled(),true);
    assert.equal(await page.locator('[id="bodyWidth-error"]').textContent()==='',false);
    await width.focus();await width.press('Escape');
    assert.equal(await page.locator('#export').isDisabled(),false);
    await page.locator('[aria-label="Reset Body width"]').click();assert.equal((await config()).applied.bodyWidth,0.32);
    await page.selectOption('#family','cottage');
    await page.locator('button[data-group="construction"]').click();
    await capture('desktop-cottage-construction');
    const chimney=page.locator('[id="chimney"]');
    const was=(await config()).applied.chimney;
    await chimney.setChecked(!was);
    assert.equal((await config()).applied.chimney,!was);
    await page.selectOption('[id="beamWeight"]','stout');
    assert.equal((await config()).applied.beamWeight,'stout');
    await page.locator('button[data-group="colors"]').click();
    const beforeColors=await config();
    await page.locator('[id="color.roof"]').fill('#335577');await page.locator('[id="color.roof"]').press('Enter');
    const afterColors=await config();
    assert.equal(afterColors.applied['color.roof'],'#335577');
    for(const [key,value] of Object.entries(beforeColors.applied))if(key!=='color.roof')assert.deepEqual(afterColors.applied[key],value);
    await page.locator('[data-key="color.roof"] .region-name').click();
    assert.match(await page.locator('#selection-note').textContent()??'',/all roof pieces/);
    await capture('desktop-cottage-colors');
    await page.locator('[data-colorway="harbor"]').click();
    assert.equal(Object.keys((await config()).requested).some(k=>k.startsWith('color.')),false);
    await page.locator('[id="color.roof"]').fill('#885522');await page.locator('[id="color.roof"]').press('Enter');
    await page.locator('[data-key="color.roof"] .control-reset').click();
    assert.equal(Object.hasOwn((await config()).requested,'color.roof'),false);
    const saved=await config(), downloadEvent=page.waitForEvent('download');
    await page.locator('#save').click();const download=await downloadEvent;
    assert.deepEqual(JSON.parse(await readFile((await download.path())!,'utf8')),saved);
    await page.selectOption('#family','tree');
    await page.selectOption('#family','cottage');assert.deepEqual((await config()).applied,saved.applied);
    await page.locator('#file').setInputFiles({name:'saved.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(saved))});
    await page.waitForTimeout(100);assert.deepEqual((await config()).applied,saved.applied);
    await page.setViewportSize({width:390,height:844});
    await page.locator('button[data-group="shape"]').click();
    await capture('mobile-cottage-shape');
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
    const canvas=(await page.locator('canvas').boundingBox())!;
    assert.ok(canvas.height>=200);
    for(const id of ['save','export','family'])assert.equal(await page.locator('#'+id).isVisible(),true);
    await page.locator('button[data-group="colors"]').click();await capture('mobile-cottage-colors');
    assert.deepEqual(errors,[]);
    await writeFile(directory+'/manifest.json',JSON.stringify({provenance:await sourceProvenance(),browser:browser.version(),screenshots,configuration:await config(),checks:{numericEntry:true,invalidBlocksExport:true,sliderNodePreserved:true,gestureUndo:true,cameraPreserved:true,typedToggleChoice:true,regionIsolation:true,paletteClearsOverrides:true,regionReset:true,saveRoundTrip:true,familyMemory:true,mobileOverflow:false},errors},null,2));
  }finally{await browser.close();await server.close();}
});
