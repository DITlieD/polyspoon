import test from 'node:test';
import assert from 'node:assert/strict';
import { DesignSession } from '../src/catalog/session.ts';
import type { AssetBuild } from '../src/catalog/index.ts';
import { disposeAsset } from '../src/catalog/index.ts';
test('gesture history is per-family and invalid edits never enter history', () => {
  const s = new DesignSession();
  s.beginGesture();
  disposeAsset(s.apply({bodyWidth:0.35}));
  disposeAsset(s.apply({bodyWidth:0.4}));
  s.endGesture();
  assert.equal(s.canUndo,true);
  disposeAsset(s.undo() as AssetBuild);
  assert.equal(s.config.applied.bodyWidth,0.32);
  assert.equal(s.canUndo,false);
  disposeAsset(s.redo() as AssetBuild);
  assert.equal(s.config.applied.bodyWidth,0.4);
  disposeAsset(s.select('tree'));
  assert.equal(s.canUndo,false);
  disposeAsset(s.apply({height:5}));
  assert.throws(()=>s.apply({height:-1}));
  disposeAsset(s.undo() as AssetBuild);
  assert.equal(s.config.applied.height,4.5);
  disposeAsset(s.select('work-lantern'));
  assert.equal(s.config.applied.bodyWidth,0.4);
  disposeAsset(s.undo() as AssetBuild);
  assert.equal(s.config.applied.bodyWidth,0.32);
  s.dispose();
});
test('undo invalidates pending loads and new commits discard redo',()=>{
  const s=new DesignSession();
  disposeAsset(s.apply({bodyWidth:0.4}));
  const ticket=s.beginLoad(), snapshot=structuredClone(s.config);
  disposeAsset(s.undo() as AssetBuild);
  assert.equal(s.finishLoad(ticket,snapshot),false);
  disposeAsset(s.apply({bodyWidth:0.3}));
  assert.equal(s.canRedo,false);
  assert.equal(s.redo(),false);
  s.dispose();
});
